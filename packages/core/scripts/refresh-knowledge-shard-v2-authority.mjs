#!/usr/bin/env node

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, renameSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repositoryRoot = resolve(packageRoot, '..', '..')
const DEFAULT_AUTHORITY_ROOT = resolve(repositoryRoot, '..', 'fortemi')
const AUTHORITY_REPOSITORY = 'https://git.integrolabs.net/Fortemi/fortemi'
const AUTHORITY_COMMIT = '0c59bc6cb06cca0b1e00eba4c0fa493f3ef3b90b'
const AUTHORITY_ROOT = 'contracts/knowledge-shard/2.0.0'
const CONTRACT_SHA256 = 'ac417e23181ec80741d776b6b29fa38236091dfa649b01255aaac30ebb53969f'
const BUNDLE_SHA256 = '731700868cc93ba95e2c1d9e896df265d0757438b06fa002d9b643ab05b5f74d'
const CURRENT_RECEIPT =
  'schemas/knowledge-shard-v2.advertisement.receipt.json'
const CHANGED_AUTHORITY_FILES = ['contract.json', 'contract.schema.json']
const HISTORICAL_RECEIPTS = [
  'knowledge-shard-v2.schema.receipt.json',
  'knowledge-shard-v2.implementation.receipt.json',
  'knowledge-shard-v2.presence.receipt.json',
  'knowledge-shard-v2.fortemi-runtime.receipt.json',
  'knowledge-shard-v2.cross-repository.receipt.json',
]

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}

function parseArgs(args) {
  let authorityRoot = process.env.FORTEMI_AUTHORITY_ROOT ?? DEFAULT_AUTHORITY_ROOT
  let verify = false
  let help = false
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index]
    if (argument === '--authority-root') {
      authorityRoot = args[index + 1]
      if (!authorityRoot) throw new Error('--authority-root requires a path')
      index += 1
    } else if (argument === '--verify') {
      verify = true
    } else if (argument === '--help' || argument === '-h') {
      help = true
    } else {
      throw new Error(`Unknown argument: ${argument}`)
    }
  }
  return { authorityRoot: resolve(authorityRoot), verify, help }
}

function usage() {
  return [
    'Usage: pnpm --filter @fortemi/core shard:refresh-v2-authority [options]',
    '',
    'Options:',
    '  --authority-root <path>  Fortemi authority repository checkout.',
    '  --verify                 Verify generated bytes without writing.',
    '  --help                   Show this help.',
    '',
    `The source is fixed at Fortemi ${AUTHORITY_COMMIT}.`,
  ].join('\n')
}

function git(authorityRoot, args, encoding = 'utf8') {
  return execFileSync('git', args, {
    cwd: authorityRoot,
    encoding,
    stdio: ['ignore', 'pipe', 'pipe'],
  })
}

function authorityFile(authorityRoot, relativePath) {
  return git(
    authorityRoot,
    ['show', `${AUTHORITY_COMMIT}:${AUTHORITY_ROOT}/${relativePath}`],
    null,
  )
}

function historicalReceipt(filename) {
  const path = resolve(packageRoot, 'schemas', filename)
  const bytes = readFileSync(path)
  return {
    path: `packages/core/schemas/${filename}`,
    sha256: sha256(bytes),
    value: JSON.parse(bytes.toString('utf8')),
  }
}

function assertEqual(actual, expected, message) {
  if (actual !== expected) {
    throw new Error(`${message}: expected ${expected}, got ${actual}`)
  }
}

function createAdvertisementReceipt(authorityRoot) {
  const resolvedCommit = git(
    authorityRoot,
    ['rev-parse', `${AUTHORITY_COMMIT}^{commit}`],
  ).trim()
  assertEqual(resolvedCommit, AUTHORITY_COMMIT, 'authority commit mismatch')

  const contractBytes = authorityFile(authorityRoot, 'contract.json')
  assertEqual(sha256(contractBytes), CONTRACT_SHA256, 'authority contract digest mismatch')
  const contract = JSON.parse(contractBytes.toString('utf8'))
  assertEqual(contract.contractRevision, '21', 'authority contract revision mismatch')
  assertEqual(contract.status, 'receipt-bound-opt-in', 'authority advertisement status mismatch')
  assertEqual(contract.schemaBundle.sha256, BUNDLE_SHA256, 'authority bundle pin mismatch')

  const bundleFiles = {}
  const aggregate = createHash('sha256')
  for (const [authorityPath, expected] of Object.entries(contract.schemaBundle.files)
    .sort(([left], [right]) => left.localeCompare(right))) {
    const relativePath = authorityPath.replace(`${AUTHORITY_ROOT}/`, '')
    const bytes = authorityFile(authorityRoot, relativePath)
    assertEqual(sha256(bytes), expected, `authority file digest mismatch for ${relativePath}`)
    aggregate.update(bytes)
    bundleFiles[relativePath] = expected
  }
  assertEqual(aggregate.digest('hex'), BUNDLE_SHA256, 'authority aggregate digest mismatch')

  const historical = Object.fromEntries(
    HISTORICAL_RECEIPTS.map((filename) => {
      const receipt = historicalReceipt(filename)
      return [
        filename,
        {
          path: receipt.path,
          sha256: receipt.sha256,
          authority: receipt.value.source
            ? {
                commit: receipt.value.source.commit,
                contractSha256: receipt.value.source.contractSha256,
                schemaBundleSha256: receipt.value.schemaBundle.sha256,
              }
            : receipt.value.authority,
        },
      ]
    }),
  )

  const receipt = {
    schemaVersion: 'fortemi-react.knowledge-shard-v2-advertisement-binding.v1',
    status: 'receipt-bound-opt-in-advertised',
    source: {
      repository: AUTHORITY_REPOSITORY,
      commit: AUTHORITY_COMMIT,
      contractPath: `${AUTHORITY_ROOT}/contract.json`,
      contractSha256: CONTRACT_SHA256,
    },
    knowledgeShard: contract.knowledgeShard,
    selection: contract.selection,
    schemaBundle: {
      sourceRoot: AUTHORITY_ROOT,
      vendoredRoot: 'schemas/knowledge-shard/2.0.0',
      aggregateAlgorithm: contract.schemaBundle.aggregateAlgorithm,
      sha256: BUNDLE_SHA256,
      files: bundleFiles,
    },
    presenceSemantics: contract.presenceSemantics,
    canonicalCorpus: {
      sourcePath: contract.canonicalCorpus.path,
      vendoredPath: 'src/__tests__/shard/fixtures/presence-semantics-v2.0.json',
      sha256: contract.canonicalCorpus.sha256,
    },
    advertisementEvidence: contract.evidence,
    historicalLineage: {
      authorityContractRevision: '20',
      authorityCommit: '6343bd899958445bbc7e7e87b0dc92a8429d5a06',
      immutable: true,
      receipts: historical,
    },
    claims: {
      exact2_0_0FullV1NamedCells: true,
      suiteWide: false,
      completeBackup: false,
      parity: false,
      persistencePlanesUnified: false,
    },
    tracking: contract.tracking,
    claimPolicy: contract.claimPolicy,
  }
  return {
    receiptBytes: Buffer.from(`${JSON.stringify(receipt, null, 2)}\n`),
    authorityFiles: Object.fromEntries(
      CHANGED_AUTHORITY_FILES.map((path) => [path, authorityFile(authorityRoot, path)]),
    ),
  }
}

function destinationForAuthorityFile(relativePath) {
  return resolve(packageRoot, 'schemas/knowledge-shard/2.0.0', relativePath)
}

function verifyBytes(path, expected) {
  const actual = readFileSync(path)
  if (!actual.equals(expected)) {
    throw new Error(`Generated authority binding drift: ${path}`)
  }
}

export function refreshKnowledgeShardV2Authority({
  authorityRoot = DEFAULT_AUTHORITY_ROOT,
  verify = false,
} = {}) {
  const generated = createAdvertisementReceipt(resolve(authorityRoot))
  const outputs = [
    ...Object.entries(generated.authorityFiles).map(([relativePath, bytes]) => ({
      path: destinationForAuthorityFile(relativePath),
      bytes,
    })),
    {
      path: resolve(packageRoot, CURRENT_RECEIPT),
      bytes: generated.receiptBytes,
    },
  ]

  if (verify) {
    for (const output of outputs) verifyBytes(output.path, output.bytes)
    return outputs.map((output) => output.path)
  }

  for (const output of outputs) {
    const temporaryPath = `${output.path}.${process.pid}.tmp`
    writeFileSync(temporaryPath, output.bytes)
    renameSync(temporaryPath, output.path)
  }
  return outputs.map((output) => output.path)
}

export function main(args = process.argv.slice(2)) {
  const options = parseArgs(args)
  if (options.help) {
    process.stdout.write(`${usage()}\n`)
    return
  }
  const outputs = refreshKnowledgeShardV2Authority(options)
  process.stdout.write(
    `${options.verify ? 'Verified' : 'Refreshed'} Fortemi revision 21 authority binding:\n`
      + outputs.map((path) => `  ${path}`).join('\n')
      + '\n',
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main()
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
    process.exitCode = 1
  }
}
